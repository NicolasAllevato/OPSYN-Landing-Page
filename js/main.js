// ========================================
// INICIALIZACIÓN
// ========================================

function getStoredLang() {
  try {
    return localStorage.getItem('opsyn-lang');
  } catch (e) {
    return null; // almacenamiento bloqueado (navegación privada estricta, etc.)
  }
}

let currentLang = ['es', 'en'].includes(getStoredLang()) ? getStoredLang() : 'es';

document.addEventListener('DOMContentLoaded', () => {
  initLanguage();
  initScrollReveal();
  initLangSwitcher();
  initNavToggle();
  initActiveNavObserver();
  initHeaderScrollState();
  updateCopyright();
});

// ========================================
// GESTOR DE IDIOMA
// ========================================

function initLanguage() {
  applyLanguage(currentLang);
}

function applyLanguage(lang) {
  currentLang = lang;
  try {
    localStorage.setItem('opsyn-lang', lang);
  } catch (e) { /* almacenamiento no disponible: no bloquea el cambio de idioma en pantalla */ }
  document.documentElement.setAttribute('lang', lang);

  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    const translation = TRANSLATIONS[lang][key];
    if (!translation) return;

    if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
      el.placeholder = translation;
    } else if (el.tagName === 'OPTION') {
      el.textContent = translation;
    } else {
      el.textContent = translation;
    }
  });

  document.querySelectorAll('.lang-btn').forEach(btn => {
    const isActive = btn.getAttribute('data-lang') === lang;
    btn.classList.toggle('active', isActive);
    btn.setAttribute('aria-pressed', String(isActive));
  });

  updateCopyright();
}

function updateCopyright() {
  const copyright = document.getElementById('copyright');
  if (copyright) {
    copyright.textContent = currentLang === 'es'
      ? '© 2026 OPSYN. Todos los derechos reservados.'
      : '© 2026 OPSYN. All rights reserved.';
  }
}

// ========================================
// SELECTOR DE IDIOMA
// ========================================

function initLangSwitcher() {
  document.querySelectorAll('.lang-btn').forEach(btn => {
    btn.addEventListener('click', (e) => {
      const lang = e.currentTarget.getAttribute('data-lang');
      applyLanguage(lang);
    });
  });
}

// ========================================
// MENÚ MÓVIL
// ========================================

function initNavToggle() {
  const toggle = document.querySelector('.nav-toggle');
  const menu = document.getElementById('nav-menu');
  if (!toggle || !menu) return;

  toggle.addEventListener('click', () => {
    const isOpen = menu.classList.toggle('is-open');
    toggle.setAttribute('aria-expanded', String(isOpen));
    toggle.setAttribute('aria-label', isOpen ? 'Cerrar menú' : 'Abrir menú');
  });

  menu.querySelectorAll('.nav-link').forEach(link => {
    link.addEventListener('click', () => {
      menu.classList.remove('is-open');
      toggle.setAttribute('aria-expanded', 'false');
    });
  });
}

// ========================================
// FONDO DEL HEADER AL HACER SCROLL
// ========================================

function initHeaderScrollState() {
  const header = document.querySelector('.header');
  if (!header) return;

  let ticking = false;

  const update = () => {
    header.classList.toggle('is-scrolled', window.scrollY > 12);
    ticking = false;
  };

  window.addEventListener('scroll', () => {
    if (ticking) return;
    ticking = true;
    requestAnimationFrame(update);
  }, { passive: true });

  update();
}

// ========================================
// SCROLL REVEAL (Animaciones)
// ========================================

function initScrollReveal() {
  const targets = document.querySelectorAll('.reveal-on-scroll, .fade-in');
  if (!targets.length) return;

  if (!('IntersectionObserver' in window)) {
    targets.forEach(el => el.classList.add('is-visible'));
    return;
  }

  const observer = new IntersectionObserver((entries) => {
    entries.forEach(entry => {
      if (entry.isIntersecting) {
        entry.target.classList.add('is-visible');
        observer.unobserve(entry.target);
      }
    });
  }, {
    threshold: 0.15,
    rootMargin: '0px 0px -50px 0px'
  });

  targets.forEach(el => observer.observe(el));
}

// ========================================
// NAV ACTIVA (IntersectionObserver, sin scroll listener)
// ========================================

function initActiveNavObserver() {
  const sections = document.querySelectorAll('section[id]');
  const navLinks = document.querySelectorAll('.nav-link');
  if (!sections.length || !navLinks.length || !('IntersectionObserver' in window)) return;

  const setActive = (id) => {
    navLinks.forEach(link => {
      link.classList.toggle('active', link.getAttribute('href') === `#${id}`);
    });
  };

  const observer = new IntersectionObserver((entries) => {
    const visible = entries
      .filter(entry => entry.isIntersecting)
      .sort((a, b) => b.intersectionRatio - a.intersectionRatio)[0];

    if (visible) setActive(visible.target.id);
  }, {
    rootMargin: '-40% 0px -50% 0px',
    threshold: [0, 0.25, 0.5, 0.75, 1]
  });

  sections.forEach(section => observer.observe(section));
}

// ========================================
// SMOOTH SCROLL PARA ENLACES
// (El formulario de contacto se maneja en js/sections/contact.js)
// ========================================

document.querySelectorAll('a[href^="#"]').forEach(anchor => {
  anchor.addEventListener('click', function (e) {
    const href = this.getAttribute('href');
    if (href === '#' || href === '') return;

    const target = document.querySelector(href);
    if (target) {
      e.preventDefault();
      target.scrollIntoView({ behavior: 'smooth' });
    }
  });
});
